def score_sellers(req: dict, budget: int, reached: list[str], ctx: dict) -> list[dict]:
    scores = []
    for sid in reached:
        s = next(x for x in ctx["sellers"] if x["id"] == sid)
        list_fen = yuan_to_fen(s["listPrice"])
        reject = None
        if req["conditionMin"] is not None and s["listed"]["grade"] < req["conditionMin"]:
            reject = f"品相 {format_grade(s['listed']['grade'])} 低于要求 {format_grade(req['conditionMin'])}"
        elif req["noNotes"] is True and s["listed"]["hasNotes"]:
            reject = "标注有笔记"
        eligible = reject is None
        condition_fit = 40 if eligible else 0
        price_fit = 35 if list_fen <= budget else max(0, 35 - ((list_fen - budget) * 100) // budget)
        reputation_fit = pct_of(s["reputation"], 25)
        scores.append({
            "sellerId": s["id"],
            "sellerName": s["name"],
            "grade": s["listed"]["grade"],
            "hasNotes": s["listed"]["hasNotes"],
            "listPrice": s["listPrice"],
            "reputation": s["reputation"],
            "style": s["style"],
            "eligible": eligible,
            "rejectReason": reject,
            "conditionFit": condition_fit,
            "priceFit": price_fit if eligible else 0,
            "reputationFit": reputation_fit if eligible else 0,
            "total": condition_fit + price_fit + reputation_fit if eligible else 0,
        })
    return sorted(scores, key=lambda x: (-x["total"], x["listPrice"], x["sellerId"]))


def ask_condition(seller: dict, req: dict, ctx: dict) -> dict:
    question = fill(ctx["buyer"]["reasonTemplates"]["askCondition"], {
        "wantGrade": "品相不限" if req["conditionMin"] is None else f"{format_grade(req['conditionMin'])}及以上",
        "wantNotes": "无笔记" if req["noNotes"] is True else "笔记不限",
    })
    tone = ctx["seller"]["toneRules"]["styles"][seller["style"]]
    a = seller["actual"]
    reply = fill(tone["reply"], {
        "grade": format_grade(a["grade"]),
        "notes": "有笔记" if a["hasNotes"] else "无笔记",
        "defects": f"{a['defects']}。" if a["defects"] else "",
    }).strip()
    gaps = []
    if req["conditionMin"] is not None and a["grade"] < req["conditionMin"]:
        gaps.append(f"实际 {format_grade(a['grade'])}，低于要求的 {format_grade(req['conditionMin'])}")
