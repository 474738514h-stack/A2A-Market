def _type_of(v) -> list[str]:
    if v is None:
        return ["null"]
    if isinstance(v, list):
        return ["array"]
    if isinstance(v, bool):
        return ["boolean"]
    if isinstance(v, (int, float)):
        is_int = isinstance(v, int) or (isinstance(v, float) and v.is_integer())
        return ["number", "integer"] if is_int else ["number"]
    if isinstance(v, str):
        return ["string"]
    if isinstance(v, dict):
        return ["object"]
    return ["unknown"]


def _num(v) -> str:
    return str(int(v)) if isinstance(v, float) and v.is_integer() else str(v)


def validate(schema: dict, data, refs: dict | None = None, path: str = "$") -> list[str]:
    refs = refs or {}
    ref = schema.get("$ref")
    if isinstance(ref, str):
        target = refs.get(ref)
        if target is None:
            return [f"{path}: unresolved $ref {ref}"]
        return validate(target, data, refs, path)
    errors: list[str] = []
    t = schema.get("type")
    if t is not None:
        allowed = t if isinstance(t, list) else [t]
        actual = _type_of(data)
        if not any(a in actual for a in allowed):
            return [f"{path}: expected type {'|'.join(allowed)}"]
    en = schema.get("enum")
    if isinstance(en, list) and not any(type(e) is type(data) and e == data for e in en):
        errors.append(f"{path}: not in enum")
    is_number = isinstance(data, (int, float)) and not isinstance(data, bool)
    if is_number:
        mn, mx = schema.get("minimum"), schema.get("maximum")
        if isinstance(mn, (int, float)) and data < mn:
            errors.append(f"{path}: below minimum {_num(mn)}")
        if isinstance(mx, (int, float)) and data > mx:
            errors.append(f"{path}: above maximum {_num(mx)}")
    if isinstance(data, str):
        n = len(data.encode("utf-16-le")) // 2  # JS string length counts UTF-16 code units
        if isinstance(schema.get("minLength"), int) and n < schema["minLength"]:
            errors.append(f"{path}: shorter than {schema['minLength']}")
        if isinstance(schema.get("maxLength"), int) and n > schema["maxLength"]:
            errors.append(f"{path}: longer than {schema['maxLength']}")
    if isinstance(data, dict):
        props = schema.get("properties") or {}
        for key in schema.get("required") or []:
            if key not in data:
                errors.append(f"{path}.{key}: required")
        for key, sub in props.items():
            if key in data:
                errors.extend(validate(sub, data[key], refs, f"{path}.{key}"))
        if schema.get("additionalProperties") is False:
            for key in data:
                if key not in props:
                    errors.append(f"{path}.{key}: additional property not allowed")
    if isinstance(data, list) and schema.get("items"):
        for i, item in enumerate(data):
            errors.extend(validate(schema["items"], item, refs, f"{path}[{i}]"))
    return errors


