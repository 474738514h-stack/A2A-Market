def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="A2A 二手书协商代理 · 离线评测（演示数据 · 脚本模拟）")
    ap.add_argument("--cases", default=str(EVAL_DIR / "cases.jsonl"), help="样本文件（jsonl），缺失时报错退出")
    ap.add_argument("--out-dir", default=str(EVAL_DIR), help="报告输出目录，默认 eval/")
    ap.add_argument("--bench-only", action="store_true", help="只运行 TS/Python 基准比对")
    ap.add_argument("--rerun", metavar="TASK_ID", help="对指定任务的冻结样本快照复跑")
    ap.add_argument("--mark-fixed", metavar="CASE_ID", help="把失败样本标记为 fixed_pending_rerun（需配合 --task）")
    ap.add_argument("--task", metavar="TASK_ID")
    ap.add_argument("--regenerate", action="store_true", help="用脚本内嵌的 30 条样本写出 --cases 文件")
    ap.add_argument("--sync-embedded", action="store_true", help="用 config/ 与 mock/ 刷新脚本内嵌默认值")
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(line_buffering=True)

    if args.sync_embedded:
        return do_sync_embedded()
    if args.regenerate:
        path = Path(args.cases)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("".join(json.dumps(c, ensure_ascii=False) + "\n" for c in EMBEDDED_CASES), encoding="utf-8")
        print(f"[ok] 已写出 {len(EMBEDDED_CASES)} 条样本到 {path}（{DATASET_VERSION}）")
        return 0
    if args.mark_fixed:
        if not args.task:
            ap.error("--mark-fixed 需要同时提供 --task")
        return do_mark_fixed(args)

    ctx, source = load_context()
    bench = run_benchmark(ctx, source, verbose=args.verbose)
    if bench["status"] == "failed":
        print("[error] TS 与 Python 引擎输出不一致，停止评测（不写任何报告）", file=sys.stderr)
        return 3
    if args.bench_only:
        return 0
    return do_run(args, ctx, source, bench)


if __name__ == "__main__":
    sys.exit(main())
