METRIC_DEFS = {
    "negotiation_success_rate": {"label": "协商成功率", "unit": "%", "target": "≥70%", "direction": "higher",
                                 "definition": "成交会话数 / 进入议价（已匹配卖家）的会话数"},
    "avg_rounds": {"label": "平均协商轮次", "unit": "轮", "target": "≤5 轮", "direction": "lower",
                   "definition": "成交会话的 stats.rounds 平均值"},
    "budget_deviation": {"label": "成交价与预算偏差", "unit": "%", "target": "≤10%", "direction": "lower",
                         "definition": "成交会话 |成交价 − 预算| / 预算 的平均值"},
    "guardrail_trigger_rate": {"label": "护栏触发率", "unit": "%", "target": "≤15%", "direction": "lower",
                               "definition": "至少触发 1 次护栏事件的会话数 / 全部会话数"},
    "parse_success_rate": {"label": "结构化输出解析成功率", "unit": "%", "target": "≥95%", "direction": "higher",
                           "definition": "通过 message.schema.json 校验的消息数 / 生成的消息总数（含重试）"},
}
TARGET_STATUS = "[待验证]"


def score_case(case: dict, res: dict) -> dict:
    exp = case["expected"]
    out = res["outcome"]
    match = res["match"]
    seller_id = match["sellerId"] if match else None
    guards = sorted({e["ruleId"] for e in res["guardrailEvents"]})
    reasons = []
    if out["status"] != exp["outcome"]:
        reasons.append(f"outcome 期望 {exp['outcome']}，实际 {out['status']}（{out['detail']}）")
    if exp.get("sellerId") and exp["sellerId"] != seller_id:
        reasons.append(f"匹配卖家期望 {exp['sellerId']}，实际 {seller_id}")
    missing = [g for g in exp.get("guardrails", []) if g not in guards]
    if missing:
        reasons.append(f"缺少期望的护栏事件：{', '.join(missing)}")
    draft = res["dealDraft"]
    return {
        "caseId": case["caseId"],
        "passed": not reasons,
        "reasons": reasons,
        "actual": {
            "outcome": out["status"],
            "round": out["round"],
            "sellerId": seller_id,
            "dealPrice": draft["price"] if draft else None,
            "budget": res["requirement"]["budget"] if res["requirement"] else None,
            "guardrails": guards,
            "stats": res["stats"],
        },
    }


def _pct(n: float, d: float):
    return None if d == 0 else round(n * 100 / d, 2)


def compute_metrics(results: list[dict]) -> dict:
    a = [r["actual"] for r in results]
    negotiated = [x for x in a if x["sellerId"] is not None]
    deals = [x for x in a if x["outcome"] == "deal"]
    attempts = sum(x["stats"]["messageAttempts"] for x in a)
    valid = sum(x["stats"]["messageValid"] for x in a)
    values = {
        "negotiation_success_rate": (_pct(len(deals), len(negotiated)), {"numerator": len(deals), "denominator": len(negotiated)}),
        "avg_rounds": (round(sum(x["stats"]["rounds"] for x in deals) / len(deals), 2) if deals else None, {"n": len(deals)}),
        "budget_deviation": (
            round(sum(abs(x["dealPrice"] - x["budget"]) / x["budget"] for x in deals) * 100 / len(deals), 2) if deals else None,
            {"n": len(deals),
             "meanAbsYuan": round(sum(abs(x["dealPrice"] - x["budget"]) for x in deals) / len(deals), 2) if deals else None}),
        "guardrail_trigger_rate": (_pct(sum(1 for x in a if x["guardrails"]), len(a)),
                                   {"numerator": sum(1 for x in a if x["guardrails"]), "denominator": len(a)}),
        "parse_success_rate": (_pct(valid, attempts), {"numerator": valid, "denominator": attempts}),
    }
    return {
        k: {**METRIC_DEFS[k], "value": v, "detail": d, "targetStatus": TARGET_STATUS}
        for k, (v, d) in values.items()
    }


