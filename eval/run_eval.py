def yuan_to_fen(yuan) -> int:
    return int(math.floor(yuan * 100 + 0.5))  # == Math.round for non-negative values


def fen_to_yuan(fen: int) -> float:
    return fen / 100


def pct_of(fen: int, pct: int) -> int:
    return (fen * pct) // 100


def format_yuan(fen: int) -> str:
    whole, frac = fen // 100, fen % 100
    if frac == 0:
        return str(whole)
    if frac % 10 == 0:
        return f"{whole}.{frac // 10}"
    return f"{whole}.{frac:02d}"


def parse_yuan_to_fen(text: str) -> int:
    whole, _, frac = text.partition(".")
    return int(whole) * 100 + int((frac + "00")[:2])


def format_grade(grade: int) -> str:
    if grade >= 100:
        return "全新"
    if grade % 10 == 0:
        return f"{grade // 10}成新"
    return f"{grade // 10}.{grade % 10}成新"


def format_condition(grade: int, has_notes: bool) -> str:
    return f"{format_grade(grade)}·{'有笔记' if has_notes else '无笔记'}"


def format_requirement_condition(condition_min, no_notes) -> str:
    g = "品相不限" if condition_min is None else f"≥{format_grade(condition_min)}"
    n = "无笔记" if no_notes is True else "笔记不限"
    return f"{g}·{n}"


_FILL_RE = re.compile(r"\{(\w+)\}", re.ASCII)


def fill(template: str, vars: dict) -> str:
    return _FILL_RE.sub(lambda m: vars.get(m.group(1), m.group(0)), template)


