CN_DIGITS = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7, "八": 8, "九": 9}
RE_TITLE = re.compile(r"《([^》]{1,40})》")
RE_GRADE_NUM = re.compile(r"([0-9](?:\.[0-9])?)\s*成新")
RE_GRADE_CN = re.compile(r"([一二三四五六七八九])成新")
RE_GRADE_NEW = re.compile(r"全新")
RE_NOTES_OK = re.compile(r"(笔记无所谓|有笔记也行|有笔记没关系|可以有笔记|笔记不限)")
RE_NOTES_NO = re.compile(r"(无笔记|没有笔记|不要笔记|没笔记|无划线|不要划线|没有划线)")
RE_BUDGET = re.compile(r"预算\s*[:：]?\s*([0-9]+(?:\.[0-9]{1,2})?)\s*(?:元|块)?")
RE_PRICE = re.compile(r"([0-9]+(?:\.[0-9]{1,2})?)\s*(?:元|块)(?:以内|以下|之内)?")


def parse_requirement_text(text: str, books: list[dict]) -> tuple[dict, int | None]:
    title = book_id = title_text = None
    title_conf = 0
    mt = RE_TITLE.search(text)
    if mt:
        title = mt.group(1).strip()
        title_text = mt.group(0)
        book = next((b for b in books if b["title"] == title or title in b["aliases"]), None)
        if book:
            book_id, title, title_conf = book["id"], book["title"], 0.98
        else:
            title_conf = 0.6
    else:
        for b in books:
            name = next((n for n in [b["title"], *b["aliases"]] if n in text), None)
            if name:
                title, book_id, title_text, title_conf = b["title"], b["id"], name, 0.85
                break

    condition_min = cond_text = None
    cond_conf = 0.5
    mg, mc = RE_GRADE_NUM.search(text), RE_GRADE_CN.search(text)
    if mg:
        whole, _, frac = mg.group(1).partition(".")
        condition_min = int(whole) * 10 + int(frac or "0")
        cond_conf, cond_text = 0.95, mg.group(0)
    elif RE_GRADE_NEW.search(text):
        condition_min, cond_conf, cond_text = 100, 0.9, "全新"
    elif mc:
        condition_min, cond_conf, cond_text = CN_DIGITS[mc.group(1)] * 10, 0.9, mc.group(0)

    no_notes = notes_text = None
    notes_conf = 0.6
    mok, mno = RE_NOTES_OK.search(text), RE_NOTES_NO.search(text)
    if mok:
        no_notes, notes_conf, notes_text = False, 0.9, mok.group(0)
    elif mno:
        no_notes, notes_conf, notes_text = True, 0.92, mno.group(0)

    budget_fen = budget_text = None
    budget_conf = 0
    mb, mp = RE_BUDGET.search(text), RE_PRICE.search(text)
    if mb:
        budget_fen, budget_conf, budget_text = parse_yuan_to_fen(mb.group(1)), 0.97, mb.group(0).strip()
    elif mp:
        budget_fen, budget_conf, budget_text = parse_yuan_to_fen(mp.group(1)), 0.85, mp.group(0).strip()
    if budget_fen is not None and budget_fen <= 0:
        budget_fen, budget_conf = None, 0

    missing = []
    if title is None:
        missing.append("title")
    if budget_fen is None:
        missing.append("budget")

    req = {
        "title": title,
        "bookId": book_id,
        "conditionMin": condition_min,
        "noNotes": no_notes,
        "budget": None if budget_fen is None else fen_to_yuan(budget_fen),
        "confidence": {"title": title_conf, "condition": cond_conf, "notes": notes_conf, "budget": budget_conf},
        "matchedText": {"title": title_text, "condition": cond_text, "notes": notes_text, "budget": budget_text},
        "missing": missing,
    }
    return req, budget_fen


