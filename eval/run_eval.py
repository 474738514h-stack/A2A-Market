def _is_num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def deep_diff(expected, actual, path="$") -> list[str]:
    if _is_num(expected) and _is_num(actual):
        same = abs(expected - actual) < 1e-9 and round(expected * 100) == round(actual * 100)
        return [] if same else [f"{path}: number {expected!r} != {actual!r}"]
    if type(expected) is not type(actual):
        return [f"{path}: type {type(expected).__name__} != {type(actual).__name__} ({expected!r} vs {actual!r})"]
    if isinstance(expected, dict):
        out = []
        for k in sorted(set(expected) | set(actual)):
            if k not in actual:
                out.append(f"{path}.{k}: missing in python output")
            elif k not in expected:
                out.append(f"{path}.{k}: extra key in python output")
            else:
                out.extend(deep_diff(expected[k], actual[k], f"{path}.{k}"))
        return out
    if isinstance(expected, list):
        out = [] if len(expected) == len(actual) else [f"{path}: length {len(expected)} != {len(actual)}"]
        for i, (e, a) in enumerate(zip(expected, actual)):
            out.extend(deep_diff(e, a, f"{path}[{i}]"))
        return out
    return [] if expected == actual else [f"{path}: {expected!r} != {actual!r}"]


def _last_seq(res: dict) -> int:
    seqs = [x["seq"] for k in ("messages", "guardrailEvents", "toolCalls") for x in res[k]]
    return max(seqs) if seqs else 0


def _count_numbers(v) -> int:
    if _is_num(v):
        return 1
    if isinstance(v, dict):
        return sum(_count_numbers(x) for x in v.values())
    if isinstance(v, list):
        return sum(_count_numbers(x) for x in v)
    return 0


def run_benchmark(ctx: dict, source: dict, verbose: bool = False) -> dict:
    path = ROOT / "fixtures" / "benchmark.json"
    if not path.exists():
        warn("fixtures/benchmark.json 不存在，跳过 TS/Python 基准比对（脚本单独分发时属正常）")
        return {"status": "skipped", "reason": "fixture_missing", "cases": 0}
    fixture = json.loads(path.read_text(encoding="utf-8"))
    print(f"[bench] fixtures/benchmark.json · fixtureVersion {fixture['fixtureVersion']} · engine TS {fixture['engineVersion']} / PY {ENGINE_VERSION}")
    if fixture["engineVersion"] != ENGINE_VERSION:
        print(f"[bench] ✗ engineVersion 不一致：TS {fixture['engineVersion']} vs PY {ENGINE_VERSION}")
    hash_ok = True
    for rel, h in fixture["configHashes"].items():
        p = ROOT / rel
        actual = hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None
        if actual != h:
            hash_ok = False
            warn(f"{rel} 的哈希与 fixture 生成时不同：fixture 可能过期，请运行 npm run bench:gen")
    if any(v == "embedded" for v in source.values()):
        warn("部分配置来自内嵌默认值，基准比对结果仅代表内嵌版本")
    failed = 0
    results = []
    for case in fixture["cases"]:
        exp = case["expected"]
        act = json.loads(json.dumps(run_session(case["input"], ctx), ensure_ascii=False))
        diffs = deep_diff(exp, act)
        eo, ao = exp["outcome"], act["outcome"]
        checks = {
            "outcome": (f"{eo['status']}@{eo['round']}", f"{ao['status']}@{ao['round']}"),
            "messages": (len(exp["messages"]), len(act["messages"])),
            "events": (len(exp["guardrailEvents"]), len(act["guardrailEvents"])),
            "lastSeq": (_last_seq(exp), _last_seq(act)),
            "stats": (json.dumps(exp["stats"], sort_keys=True), json.dumps(act["stats"], sort_keys=True)),
        }
        ok = not diffs and all(a == b for a, b in checks.values())
        failed += 0 if ok else 1
        mark = "✔" if ok else "✗"
        print(f"[bench] {mark} {case['id']}")
        for name, (e, a) in checks.items():
            print(f"[bench]     {name:<8} TS {e}  |  PY {a}  {'==' if e == a else '!='}")
        print(f"[bench]     numbers  {_count_numbers(exp)} 个数值逐个比对（精确到分）· 结构差异 {len(diffs)} 处")
        for d in diffs[: (len(diffs) if verbose else 10)]:
            print(f"[bench]       - {d}")
        results.append({"id": case["id"], "passed": ok, "diffs": len(diffs)})
    status = "passed" if failed == 0 else "failed"
    print(f"[bench] 结果：{len(results) - failed}/{len(results)} 一致 · 配置哈希{'一致' if hash_ok else '不一致'} → {status}")
    return {"status": status, "cases": len(results), "failed": failed, "configHashesMatch": hash_ok, "results": results}


