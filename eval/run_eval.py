def load_context() -> tuple[dict, dict]:
    raw: dict = {}
    source: dict = {}
    for key, rel in CONTEXT_FILES.items():
        path = ROOT / rel
        try:
            raw[key] = json.loads(path.read_text(encoding="utf-8"))
            source[key] = rel
            emb = EMBEDDED_DEFAULTS.get(key)
            if emb is not None and emb != raw[key]:
                warn(f"{rel} 与脚本内嵌默认值不一致（以文件为准）；可运行 --sync-embedded 同步")
        except (OSError, json.JSONDecodeError) as exc:
            if key not in EMBEDDED_DEFAULTS:
                raise SystemExit(f"[error] 读取 {rel} 失败且无内嵌默认值：{exc}")
            warn(f"读取 {rel} 失败（{exc.__class__.__name__}），改用脚本内嵌默认值")
            raw[key] = copy.deepcopy(EMBEDDED_DEFAULTS[key])
            source[key] = "embedded"
    ctx = {
        "buyer": raw["buyer"],
        "seller": raw["seller"],
        "messageSchema": raw["messageSchema"],
        "toolsSchema": raw["toolsSchema"],
        "books": raw["books"]["books"],
        "sellers": raw["sellers"]["sellers"],
    }
    return ctx, source


