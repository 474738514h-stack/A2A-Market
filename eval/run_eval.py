PII_PATTERNS = [
    ("身份证号", re.compile(r"(?<![0-9])[1-9][0-9]{16}[0-9Xx](?![0-9A-Za-z])"), "[身份证号已隐藏]"),
    ("手机号", re.compile(r"(?<![0-9])1[3-9][0-9]{9}(?![0-9])"), "[手机号已隐藏]"),
]


class GuardrailViolation(AssertionError):
    pass


def redact_pii(text: str) -> tuple[str, list[dict]]:
    out, hits = text, []
    for label, rx, mask in PII_PATTERNS:
        found = rx.findall(out)
        if found:
            hits.append({"label": label, "count": len(found)})
            out = rx.sub(mask, out)
    return out, hits


def pii_detail(hit: dict) -> str:
    return f"已隐藏 {hit['count']} 处{hit['label']}"


def clamp_swing(prev: int, nxt: int, max_swing_pct: int) -> tuple[int, bool, int]:
    max_move = pct_of(prev, max_swing_pct)
    diff = abs(nxt - prev)
    swing_pct = (diff * 100) // prev if prev > 0 else 0
    if diff <= max_move:
        return nxt, False, swing_pct
    return (prev + max_move if nxt > prev else prev - max_move), True, swing_pct


def swing_detail(actor_label: str, swing_pct: int, max_swing_pct: int, price: int) -> str:
    return f"{actor_label}报价变动 {swing_pct}% 超过 {max_swing_pct}%，已截断为 {format_yuan(price)} 元"


def assert_buyer_price(price: int, budget: int) -> None:
    if price > budget:
        raise GuardrailViolation(f"G-BUDGET: buyer price {price} exceeds budget {budget}")


def assert_round(rnd: int, max_rounds: int) -> None:
    if rnd > max_rounds:
        raise GuardrailViolation(f"G-ROUNDS: round {rnd} exceeds max {max_rounds}")


def assert_swing(prev: int, nxt: int, max_swing_pct: int) -> None:
    if abs(nxt - prev) > pct_of(prev, max_swing_pct):
        raise GuardrailViolation(f"G-SWING: move {prev}->{nxt} exceeds {max_swing_pct}%")


def assert_seller_floor(price: int, floor: int) -> None:
    if price < floor:
        raise GuardrailViolation(f"S-FLOOR: seller price {price} below floor {floor}")


