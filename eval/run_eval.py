def now_iso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def write_json_atomic(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def write_jsonl_atomic(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    os.replace(tmp, path)


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def baseline_key(dataset_version: str, cases_hash: str) -> str:
    return f"{dataset_version}|{cases_hash}|{METRIC_DEF_VERSION}"


def compare_with_baseline(out_dir: Path, key: str, task_id: str, run_no: int, metrics: dict, run_at: str) -> dict:
    path = out_dir / "baseline.json"
    baselines = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    base = baselines.get(key)
    if base is None:
        baselines[key] = {"taskId": task_id, "runNo": run_no, "establishedAt": run_at,
                          "metrics": {k: v["value"] for k, v in metrics.items()}}
        write_json_atomic(path, baselines)
        return {"status": "baseline_established", "key": key,
                "note": "首个成功运行，仅建立基线，不计算差异"}
    deltas = {}
    for k, v in metrics.items():
        b = base["metrics"].get(k)
        deltas[k] = None if (b is None or v["value"] is None) else round(v["value"] - b, 2)
    return {"status": "compared", "key": key, "baseline": {"taskId": base["taskId"], "runNo": base["runNo"],
            "establishedAt": base["establishedAt"]}, "deltas": deltas}


def evaluate(cases: list[dict], ctx: dict) -> list[dict]:
    results = []
    for c in cases:
        res = run_session(c["input"], ctx)
        results.append({**score_case(c, res), "input": c["input"], "expected": c["expected"]})
    return results


def merge_failures(task_id: str, run_no: int, results: list[dict], previous: list[dict], at: str) -> list[dict]:
    prev = {f["caseId"]: f for f in previous}
    merged = []
    by_id = {r["caseId"]: r for r in results}
    for case_id in sorted(set(prev) | {r["caseId"] for r in results if not r["passed"]}):
        r = by_id.get(case_id)
        f = copy.deepcopy(prev.get(case_id)) or {
            "taskId": task_id, "caseId": case_id, "status": "open", "firstSeenRun": run_no, "history": []}
        if r is None:
            merged.append(f)
            continue
        old = f["status"]
        if r["passed"]:
            if old != "fixed":
                f["fixedInRun"] = run_no
            f["status"] = "fixed"
        else:
            f["status"] = "open"
            f.pop("fixedInRun", None)
        f.update({"input": r["input"], "expected": r["expected"], "actual": r["actual"],
                  "reasons": r["reasons"], "lastCheckedRun": run_no, "lastCheckedAt": at})
        f["history"].append({"run": run_no, "at": at, "passed": r["passed"], "from": old if case_id in prev else None, "to": f["status"]})
        merged.append(f)
    return merged


def do_run(args, ctx: dict, source: dict, bench: dict) -> int:
    out_dir = Path(args.out_dir)
    runs_dir = out_dir / "runs"
    rerun = args.rerun is not None

    if rerun:
        task_dir = runs_dir / args.rerun
        task_file = task_dir / "task.json"
        if not task_file.exists():
            print(f"[error] 找不到任务 {args.rerun}（{task_file}）", file=sys.stderr)
            return 4
        task = json.loads(task_file.read_text(encoding="utf-8"))
        if not any(r["status"] == "succeeded" and r["kind"] == "initial" for r in task["runs"]):
            print(f"[error] 任务 {args.rerun} 的首次运行未成功完成，复跑不推进", file=sys.stderr)
            return 4
        cases, cases_hash = load_cases(task_dir / "cases.snapshot.jsonl")
        if cases_hash != task["casesHash"]:
            print("[error] 冻结样本快照的哈希与任务记录不一致，拒绝复跑", file=sys.stderr)
            return 4
        task_id = task["taskId"]
    else:
        try:
            cases, cases_hash = load_cases(Path(args.cases))
        except (FileNotFoundError, ValueError) as exc:
            print(f"[error] {exc}", file=sys.stderr)
            return 2
        stamp = datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")
        task_id = f"eval-{stamp}-{cases_hash[:6]}"
        task_dir = runs_dir / task_id
        task_dir.mkdir(parents=True, exist_ok=False)
        (task_dir / "cases.snapshot.jsonl").write_text(
            "".join(canonical_case_line(c) + "\n" for c in cases), encoding="utf-8")
        task = {"taskId": task_id, "createdAt": now_iso(), "datasetVersion": cases[0]["datasetVersion"],
                "casesFile": os.path.relpath(Path(args.cases).resolve(), ROOT), "casesHash": cases_hash,
                "sampleCount": len(cases), "metricDefVersion": METRIC_DEF_VERSION, "runs": []}
        task_file = task_dir / "task.json"

    run_no = len(task["runs"]) + 1
    run = {"runNo": run_no, "kind": "rerun" if rerun else "initial", "startedAt": now_iso(), "status": "running"}
    task["runs"].append(run)
    write_json_atomic(task_file, task)

    try:
        results = evaluate(cases, ctx)
        if len(results) != len(cases):
            raise RuntimeError("结果数量与样本数量不一致")
        metrics = compute_metrics(results)
        finished = now_iso()
        prev_failures = read_jsonl(task_dir / "failures.jsonl")
        failures = merge_failures(task_id, run_no, results, prev_failures, finished)
        comparison = compare_with_baseline(out_dir, baseline_key(task["datasetVersion"], cases_hash), task_id, run_no, metrics, finished)
        passed = sum(1 for r in results if r["passed"])
        report = {
            "_notice": "演示数据 · 脚本模拟。本报告由本地运行 eval/run_eval.py 生成；目标值需人工确认，一律标注 [待验证]。",
            "reportVersion": REPORT_VERSION,
            "taskId": task_id,
            "runNo": run_no,
            "runKind": run["kind"],
            "runAt": run["startedAt"],
            "finishedAt": finished,
            "datasetVersion": task["datasetVersion"],
            "casesFile": task["casesFile"],
            "casesHash": cases_hash,
            "sampleCount": len(cases),
            "metricDefVersion": METRIC_DEF_VERSION,
            "engineVersion": ENGINE_VERSION,
            "promptVersions": {"buyer": ctx["buyer"]["version"], "seller": ctx["seller"]["version"]},
            "configSource": source,
            "benchmark": {k: v for k, v in bench.items() if k != "results"},
            "metrics": metrics,
            "casePassRate": {"passed": passed, "total": len(results), "value": _pct(passed, len(results))},
            "outcomeBreakdown": {s: sum(1 for r in results if r["actual"]["outcome"] == s)
                                 for s in sorted({r["actual"]["outcome"] for r in results})},
            "comparison": comparison,
            "failures": {"open": sum(1 for f in failures if f["status"] == "open"),
                         "fixed_pending_rerun": sum(1 for f in failures if f["status"] == "fixed_pending_rerun"),
                         "fixed": sum(1 for f in failures if f["status"] == "fixed"),
                         "file": "eval/failures.jsonl"},
        }
        write_jsonl_atomic(task_dir / "failures.jsonl", failures)
        write_json_atomic(task_dir / f"report.run{run_no}.json", report)
        write_jsonl_atomic(task_dir / f"results.run{run_no}.jsonl", results)
        write_json_atomic(out_dir / "latest_report.json", report)
        write_jsonl_atomic(out_dir / "failures.jsonl", failures)
        run.update({"status": "succeeded", "finishedAt": finished, "passed": passed, "total": len(results)})
        write_json_atomic(task_file, task)
    except KeyboardInterrupt:
        run.update({"status": "cancelled", "finishedAt": now_iso()})
        write_json_atomic(task_file, task)
        print(f"\n[cancelled] 任务 {task_id} 第 {run_no} 次运行已取消：未写入 latest_report.json / failures.jsonl", file=sys.stderr)
        return 130
    except Exception as exc:  # noqa: BLE001
        run.update({"status": "failed", "finishedAt": now_iso(), "error": f"{exc.__class__.__name__}: {exc}"})
        write_json_atomic(task_file, task)
        print(f"[failed] 任务 {task_id} 第 {run_no} 次运行失败：{exc}；未写入 latest_report.json / failures.jsonl", file=sys.stderr)
        return 1

    print_summary(report, results, failures)
    return 0


def print_summary(report: dict, results: list[dict], failures: list[dict]) -> None:
    print("")
    print(f"[eval] 任务 {report['taskId']} · 第 {report['runNo']} 次（{report['runKind']}）· {report['finishedAt']}")
    print(f"[eval] 样本集 {report['datasetVersion']} · {report['sampleCount']} 条 · hash {report['casesHash'][:12]} · 指标定义 {report['metricDefVersion']}")
    for m in report["metrics"].values():
        val = "—" if m["value"] is None else f"{m['value']}{'' if m['unit'] == '轮' else m['unit']}{' 轮' if m['unit'] == '轮' else ''}"
        print(f"[eval]   {m['label']:<14} {val:>10}   目标 {m['target']} {m['targetStatus']}")
    cp = report["casePassRate"]
    print(f"[eval]   样本符合预期     {cp['passed']}/{cp['total']}")
    print(f"[eval]   结局分布         {report['outcomeBreakdown']}")
    cmp_ = report["comparison"]
    if cmp_["status"] == "baseline_established":
        print(f"[eval] 基线：{cmp_['note']}")
    else:
        print(f"[eval] 对比基线 {cmp_['baseline']['taskId']}#run{cmp_['baseline']['runNo']}：{cmp_['deltas']}")
    for f in failures:
        print(f"[eval]   ✗ {f['caseId']} [{f['status']}] {'；'.join(f.get('reasons') or ['（本次已通过）'])}")
    print("[eval] 已写入 eval/latest_report.json 与 eval/failures.jsonl")


def do_mark_fixed(args) -> int:
    task_dir = Path(args.out_dir) / "runs" / args.task
    path = task_dir / "failures.jsonl"
    failures = read_jsonl(path)
    hit = next((f for f in failures if f["caseId"] == args.mark_fixed), None)
    if hit is None:
        print(f"[error] 任务 {args.task} 中没有失败样本 {args.mark_fixed}", file=sys.stderr)
        return 4
    if hit["status"] != "open":
        print(f"[error] {args.mark_fixed} 当前状态为 {hit['status']}，只能把 open 标记为 fixed_pending_rerun", file=sys.stderr)
        return 4
    hit["status"] = "fixed_pending_rerun"
    hit["history"].append({"at": now_iso(), "from": "open", "to": "fixed_pending_rerun", "by": "manual"})
    write_jsonl_atomic(path, failures)
    latest = Path(args.out_dir) / "latest_report.json"
    if latest.exists() and json.loads(latest.read_text(encoding="utf-8")).get("taskId") == args.task:
        write_jsonl_atomic(Path(args.out_dir) / "failures.jsonl", failures)
    print(f"[ok] {args.mark_fixed} → fixed_pending_rerun；运行 --rerun {args.task} 通过后才会变为 fixed")
    return 0


def do_sync_embedded() -> int:
    me = Path(__file__).resolve()
    src = me.read_text(encoding="utf-8")
    data = {k: json.loads((ROOT / rel).read_text(encoding="utf-8")) for k, rel in CONTEXT_FILES.items()}
    begin, end = "# BEGIN " + "EMBEDDED DEFAULTS", "# END " + "EMBEDDED DEFAULTS"
    block = (
        f"{begin} (generated by --sync-embedded; do not edit by hand)\n"
        f"EMBEDDED_DEFAULTS: dict = json.loads(r\'\'\'{json.dumps(data, ensure_ascii=False, indent=1)}\'\'\')\n"
        f"{end}"
    )
    new = re.sub(re.escape(begin) + r".*?" + re.escape(end), lambda _m: block, src, count=1, flags=re.S)
    me.write_text(new, encoding="utf-8")
    print(f"[ok] 已用 {', '.join(CONTEXT_FILES.values())} 刷新脚本内嵌默认值")
    return 0


