INTENT_LABEL = {"offer": "出价", "counter": "还价", "accept": "接受", "reject": "拒绝"}


class Session:
    def __init__(self, raw: str, ctx: dict):
        self.ctx = ctx
        self.stage = "parse"
        self.seq = 0
        self.budget = 0
        self.seller_id = None
        self.seller_ask = 0
        self.seller_at_floor = False
        self.buyer_last = None
        self.round = 0
        self.deal = None
        self.result = {
            "engineVersion": ENGINE_VERSION,
            "promptVersions": {"buyer": ctx["buyer"]["version"], "seller": ctx["seller"]["version"]},
            "input": {"raw": raw, "sanitized": raw},
            "requirement": None,
            "candidates": [],
            "match": None,
            "inquiry": None,
            "messages": [],
            "guardrailEvents": [],
            "toolCalls": [],
            "outcome": None,
            "dealDraft": None,
            "stats": {"rounds": 0, "messageAttempts": 0, "messageValid": 0, "parseErrors": 0},
        }

    # helpers -------------------------------------------------------------
    def safety(self, rule_id: str, key: str) -> int:
        rule = next((r for r in self.ctx["buyer"]["safetyRules"] if r["ruleId"] == rule_id), None)
        v = None if rule is None else rule.get(key)
        if not isinstance(v, int):
            raise SystemExit(f"[error] config/prompts/buyer.json: safetyRules {rule_id}.{key} missing")
        return v

    def next_seq(self) -> int:
        self.seq += 1
        return self.seq

    def event(self, rule_id, rnd, actor, action, detail):
        self.result["guardrailEvents"].append(
            {"seq": self.next_seq(), "ruleId": rule_id, "round": rnd, "actor": actor, "action": action, "detail": detail})

    def tool(self, name, actor, rnd, status, summary):
        self.result["toolCalls"].append(
            {"seq": self.next_seq(), "tool": name, "actor": actor, "round": rnd, "status": status, "summary": summary})

    def finish(self, status, rnd, detail):
        self.result["outcome"] = {"status": status, "round": rnd, "manualReview": status != "deal", "detail": detail}
        self.stage = "done"

    def seller(self) -> dict:
        return next(x for x in self.ctx["sellers"] if x["id"] == self.seller_id)

    def emit(self, actor, rnd, source, produce, status="sent") -> bool:
        max_retries = self.safety("G-SCHEMA", "maxRetries")
        stats = self.result["stats"]
        for attempt in range(1, 2 + max_retries):
            payload = produce(attempt)
            errors = validate(self.ctx["messageSchema"], payload)
            valid = not errors
            stats["messageAttempts"] += 1
            if valid:
                stats["messageValid"] += 1
            else:
                stats["parseErrors"] += 1
            self.result["messages"].append({
                "seq": self.next_seq(), "round": rnd, "actor": actor, "tool": "make_offer", "attempt": attempt,
                "status": status if valid else "invalid", "payload": payload, "errors": errors, "source": source,
            })
            if valid:
                self.tool("make_offer", actor, rnd, "blocked" if status == "blocked" else "ok",
                          f"{INTENT_LABEL[payload['intent']]} {format_yuan(yuan_to_fen(payload['price']))} 元")
                return True
            self.tool("make_offer", actor, rnd, "error", "Schema 校验失败")
            if attempt <= max_retries:
                self.event("G-SCHEMA", rnd, actor, "retry", f"消息未通过 Schema 校验（{'; '.join(errors)}），重试 1 次")
            else:
                self.event("G-SCHEMA", rnd, actor, "escalated", "重试后仍未通过校验，停止自动议价并转人工")
        return False

    # stages --------------------------------------------------------------
    def step_parse(self):
        text, hits = redact_pii(self.result["input"]["raw"])
        self.result["input"]["sanitized"] = text
        for h in hits:
            self.event("G-PII", None, "buyer", "redacted", pii_detail(h))
        req, budget = parse_requirement_text(text, self.ctx["books"])
        errors = tool_output_errors(self.ctx, "parse_requirement", req)
        if errors:
            self.tool("parse_requirement", "buyer", None, "error", "Schema 校验失败")
            return self.finish("parse_failed", 0, f"解析结果未通过 Schema 校验：{'; '.join(errors)}")
        self.result["requirement"] = req
        if req["missing"] or budget is None:
            labels = ["书名" if m == "title" else "预算" for m in req["missing"]]
            self.tool("parse_requirement", "buyer", None, "error", f"未识别：{'、'.join(labels)}")
            return self.finish("parse_failed", 0, f"没能识别出{'和'.join(labels)}")
        self.budget = budget
        self.tool("parse_requirement", "buyer", None, "ok", requirement_summary(req, budget))
        self.stage = "broadcast"

    def step_broadcast(self):
        req = self.result["requirement"]
        reached = [] if req["bookId"] is None else [s["id"] for s in self.ctx["sellers"] if s["bookId"] == req["bookId"]]
        self.result["candidates"] = reached
        self.tool("broadcast_demand", "buyer", None, "ok" if reached else "error", f"已广播给 {len(reached)} 位卖家 Agent")
        if not reached:
            return self.finish("no_match", 0, f"暂时没有卖家在卖《{req['title']}》")
        self.stage = "match"

    def step_match(self):
        req = self.result["requirement"]
        scores = score_sellers(req, self.budget, self.result["candidates"], self.ctx)
        best = next((x for x in scores if x["eligible"]), None)
        self.result["match"] = {"sellerId": best["sellerId"] if best else None, "scores": scores}
        if not best:
            self.tool("match_seller", "buyer", None, "error", f"{len(scores)} 位卖家均不满足品相要求")
            return self.finish("no_match", 0, f"找到 {len(scores)} 位卖家，但品相都不满足你的要求")
        self.tool("match_seller", "buyer", None, "ok", f"命中 {best['sellerName']}（匹配分 {best['total']}）")
        self.seller_id = best["sellerId"]
        self.seller_ask = yuan_to_fen(self.seller()["listPrice"])
        self.stage = "inquire"

    def step_inquire(self):
        req, seller, ctx = self.result["requirement"], self.seller(), self.ctx
        inquiry = ask_condition(seller, req, ctx)
        errors = tool_output_errors(ctx, "ask_condition", inquiry["answer"])
        self.result["inquiry"] = inquiry
        if errors:
            self.tool("ask_condition", "buyer", None, "error", "Schema 校验失败")
            return self.finish("message_parse_failed", 0, f"品相回复未通过 Schema 校验：{'; '.join(errors)}")
        cond = format_condition(inquiry["answer"]["grade"], inquiry["answer"]["hasNotes"])
        self.tool("ask_condition", "buyer", None, "ok" if inquiry["satisfied"] else "error",
                  f"品相符合要求（{cond}）" if inquiry["satisfied"] else f"品相不符：{'；'.join(inquiry['gaps'])}")
        if not inquiry["satisfied"]:
            self.round = 1
            self.result["stats"]["rounds"] = 1
            gap = "；".join(inquiry["gaps"])
            self.emit("buyer", 1, {"prompt": f"buyer@{ctx['buyer']['version']}", "ruleId": ctx["buyer"]["conditionRule"]["ruleId"]},
                      lambda _a: {
                          "intent": "reject",
                          "price": fen_to_yuan(self.seller_ask),
                          "condition": format_requirement_condition(req["conditionMin"], req["noNotes"]),
                          "notes": "",
                          "reason": fill(ctx["buyer"]["reasonTemplates"]["rejectCondition"], {"gap": gap}),
                      })
            return self.finish("condition_rejected", 1, f"卖家实际品相不满足要求：{gap}")
        self.round = 1
        self.stage = "negotiate"

    def step_negotiate(self):
        ctx, req, seller = self.ctx, self.result["requirement"], self.seller()
        buyer_cfg, seller_cfg = ctx["buyer"], ctx["seller"]
        max_rounds = self.safety("G-ROUNDS", "maxRounds")
        max_swing = self.safety("G-SWING", "maxSwingPct")
        r = self.round
        assert_round(r, max_rounds)
        self.result["stats"]["rounds"] = r

        B, ask = self.budget, self.seller_ask
        list_fen, floor_fen = yuan_to_fen(seller["listPrice"]), yuan_to_fen(seller["floorPrice"])
        buyer_src = lambda rule: {"prompt": f"buyer@{buyer_cfg['version']}", "ruleId": rule}  # noqa: E731
        seller_src = lambda rule: {"prompt": f"seller@{seller_cfg['version']}", "ruleId": rule}  # noqa: E731
        buyer_cond = format_requirement_condition(req["conditionMin"], req["noNotes"])
        seller_cond = format_condition(seller["actual"]["grade"], seller["actual"]["hasNotes"])
        tpl = buyer_cfg["reasonTemplates"]
        tone = seller_cfg["toneRules"]["styles"][seller["style"]]

        open_ = pct_of(B, buyer_cfg["openingRule"]["openingRatioPct"])
        step = pct_of(B, buyer_cfg["concessionPlan"]["stepPctOfBudget"])
        planned = open_ if r == 1 else min(B, (self.buyer_last if self.buyer_last is not None else open_) + step)

        # Buyer turn
        if ask <= min(B, planned) or (self.seller_at_floor and ask <= B):
            reason_key = "acceptFloor" if self.seller_at_floor and ask > planned else "acceptAsk"
            assert_buyer_price(ask, B)
            ok = self.emit("buyer", r, buyer_src(buyer_cfg["acceptRule"]["ruleId"]), lambda _a: {
                "intent": "accept", "price": fen_to_yuan(ask), "condition": buyer_cond, "notes": "",
                "reason": fill(tpl[reason_key], {"price": format_yuan(ask)}),
            })
            if not ok:
                return self.finish("message_parse_failed", r, f"第 {r} 轮买家消息连续未通过 Schema 校验")
            self.deal = ask
            self.stage = "draft"
            return
        if self.seller_at_floor:
            over_pct = ((ask - B) * 100) // B
            if ask * 100 <= B * (100 + buyer_cfg["walkawayRule"]["nearMissPct"]):
                self.emit("buyer", r, buyer_src(buyer_cfg["acceptRule"]["ruleId"]), lambda _a: {
                    "intent": "accept", "price": fen_to_yuan(ask), "condition": buyer_cond, "notes": "",
                    "reason": fill(tpl["acceptFloor"], {"price": format_yuan(ask)}),
                }, "blocked")
                self.event("G-BUDGET", r, "buyer", "blocked",
                           f"拟接受 {format_yuan(ask)} 元，超出预算 {format_yuan(B)} 元，已拦截，需要你确认是否加价")
                return self.finish("over_budget", r, f"卖家底价 {format_yuan(ask)} 元，超出你的预算 {format_yuan(B)} 元（约 {over_pct}%）")
            last = self.buyer_last if self.buyer_last is not None else open_
            ok = self.emit("buyer", r, buyer_src(buyer_cfg["walkawayRule"]["ruleId"]), lambda _a: {
                "intent": "reject", "price": fen_to_yuan(last), "condition": buyer_cond, "notes": "",
                "reason": tpl["rejectFloor"],
            })
            if not ok:
                return self.finish("message_parse_failed", r, f"第 {r} 轮买家消息连续未通过 Schema 校验")
            return self.finish("walkaway", r, f"卖家底价 {format_yuan(ask)} 元，比你的预算高出 {over_pct}%")

        bid = planned
        if self.buyer_last is not None:
            price, clamped, swing_pct = clamp_swing(self.buyer_last, bid, max_swing)
            if clamped:
                self.event("G-SWING", r, "buyer", "clamped", swing_detail("买家", swing_pct, max_swing, price))
            bid = price
            assert_swing(self.buyer_last, bid, max_swing)
        assert_buyer_price(bid, B)
        bid_key = "counterAtCap" if bid == B else ("open" if r == 1 else "counter")
        bid_rule = buyer_cfg["openingRule"]["ruleId"] if r == 1 else buyer_cfg["concessionPlan"]["ruleId"]
        ok = self.emit("buyer", r, buyer_src(bid_rule), lambda _a: {
            "intent": "offer" if r == 1 else "counter", "price": fen_to_yuan(bid), "condition": buyer_cond,
            "notes": "", "reason": fill(tpl[bid_key], {"price": format_yuan(bid)}),
        })
        if not ok:
            return self.finish("message_parse_failed", r, f"第 {r} 轮买家消息连续未通过 Schema 校验")
        self.buyer_last = bid

        # Seller turn
        pace = seller_cfg["concessionPace"]["levels"].get(seller["concessionPace"])
        if pace is None:
            raise SystemExit(f"[error] config/prompts/seller.json: concessionPace.levels.{seller['concessionPace']} missing")
        pace_step = pct_of(list_fen - floor_fen, pace["stepPctOfGap"])
        nxt = max(floor_fen, ask - pace_step)
        seller_accepts = bid >= nxt
        notes = ""
        if r == 1 and seller["notes"]:
            notes, hits = redact_pii(seller["notes"])
            for h in hits:
                self.event("G-PII", r, "seller", "redacted", pii_detail(h))
        if not seller_accepts:
            price, clamped, swing_pct = clamp_swing(ask, nxt, max_swing)
            if clamped:
                self.event("G-SWING", r, "seller", "clamped", swing_detail("卖家", swing_pct, max_swing, price))
            nxt = price
            assert_swing(ask, nxt, max_swing)
            assert_seller_floor(nxt, floor_fen)
        at_floor = (not seller_accepts) and nxt == floor_fen
        seller_price = bid if seller_accepts else nxt
        seller_key = "accept" if seller_accepts else ("floor" if at_floor else "counter")
        seller_rule = seller_cfg["floorPrice"]["ruleId"] if at_floor else seller_cfg["concessionPace"]["ruleId"]
        glitch = seller.get("glitch")

        def produce(attempt):
            corrupt = glitch is not None and glitch["round"] == r and (attempt == 1 or glitch["mode"] == "persistent")
            if corrupt:
                return {"intent": "maybe", "price": f"{format_yuan(seller_price)}元", "condition": seller_cond,
                        "notes": notes, "reason": "这个价嘛……再看看"}
            return {"intent": "accept" if seller_accepts else "counter", "price": fen_to_yuan(seller_price),
                    "condition": seller_cond, "notes": notes,
                    "reason": fill(tone[seller_key], {"price": format_yuan(seller_price)})}

        if not self.emit("seller", r, seller_src(seller_rule), produce):
            return self.finish("message_parse_failed", r, f"第 {r} 轮卖家消息连续 2 次未通过 Schema 校验")

        if seller_accepts:
            self.deal = bid
            self.stage = "draft"
            return
        self.seller_ask = nxt
        self.seller_at_floor = at_floor
        if r >= max_rounds:
            self.event("G-ROUNDS", r, "system", "stopped", f"已达 {max_rounds} 轮上限仍未成交，停止自动议价")
            return self.finish("max_rounds", r, f"谈了 {r} 轮，卖家最新报价 {format_yuan(nxt)} 元，你的出价 {format_yuan(bid)} 元")
        self.round = r + 1

    def step_draft(self):
        seller = self.seller()
        book = next(b for b in self.ctx["books"] if b["id"] == seller["bookId"])
        price = self.deal
        draft = {
            "bookTitle": book["title"],
            "sellerId": seller["id"],
            "sellerName": seller["name"],
            "condition": format_condition(seller["actual"]["grade"], seller["actual"]["hasNotes"]),
            "price": price / 100,
            "listPrice": seller["listPrice"],
            "budget": self.budget / 100,
            "fulfillment": "快递发货 · 资金由平台模拟托管，确认收货后放款",
            "round": self.round,
        }
        errors = tool_output_errors(self.ctx, "confirm_deal", draft)
        if errors:
            self.tool("confirm_deal", "system", self.round, "error", "Schema 校验失败")
            return self.finish("message_parse_failed", self.round, f"交易草案未通过 Schema 校验：{'; '.join(errors)}")
        self.result["dealDraft"] = draft
        self.tool("confirm_deal", "system", self.round, "ok", f"生成交易草案：{format_yuan(price)} 元")
        saved = yuan_to_fen(seller["listPrice"]) - price
        self.finish("deal", self.round, f"第 {self.round} 轮以 {format_yuan(price)} 元成交，比挂牌价省 {format_yuan(saved)} 元")

    def run(self) -> dict:
        steps = {"parse": self.step_parse, "broadcast": self.step_broadcast, "match": self.step_match,
                 "inquire": self.step_inquire, "negotiate": self.step_negotiate, "draft": self.step_draft}
        for _ in range(64):
            if self.stage == "done":
                return self.result
            steps[self.stage]()
        raise RuntimeError("engine did not terminate")


def run_session(raw: str, ctx: dict) -> dict:
    return Session(raw, ctx).run()


